import XCTest
import SwiftUI
import UIKit
import QueryCraftMobileCore
@testable import QueryCraftMobileProof

@MainActor final class MobilePostgreSQLParityPresentationTests: XCTestCase {
    func testNativeStructureNewTableImportAndQueryEntryPoints() async throws {
        guard ProcessInfo.processInfo.environment["PROOF_POSTGRES_PORT"] != nil else { throw XCTSkip("Requires owned PG fixture") }
        try await MobilePostgreSQLParityTests.withSchema { schema in
            let table = MobilePostgreSQLParityTests.table(schema), object = MobilePostgreSQLParityTests.object(schema)
            try await MobilePostgreSQLParityTests.query("CREATE TABLE " + table + " (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT DEFAULT 'native')")
            try await MobilePostgreSQLParityTests.query("INSERT INTO " + table + " (name) VALUES ('原生 PG 雪')")
            let config = try MobilePostgreSQLParityTests.configuration()
            let profile = MobileConnectionProfile(id: UUID(), name: "PG 完整验收", host: config.host, port: config.port, username: config.username, database: object.database, tlsMode: .disabled, remembersPassword: false, requiresPassword: true, driver: .postgresql, schemaName: schema)
            let workspace = MobileDatabaseWorkspace(profile: profile, password: config.password, service: MobilePostgreSQLService())
            await workspace.browser.loadDatabases().value; await workspace.browser.loadObjects()?.value; await workspace.browser.selectObject(object)?.value
            XCTAssertTrue(workspace.browser.supportsSchemaEditing); XCTAssertNotNil(workspace.tableActions.onImport)
            let scene = try XCTUnwrap(UIApplication.shared.connectedScenes.compactMap { $0 as? UIWindowScene }.first)
            let previous = scene.windows.first(where: \.isKeyWindow), window = UIWindow(windowScene: scene)
            window.frame = scene.coordinateSpace.bounds; window.makeKeyAndVisible()
            defer { window.isHidden = true; previous?.makeKey(); workspace.cancelAll() }
            @MainActor func show<V: View>(_ view: V, _ name: String, dark: Bool = false, bottom: Bool = false) async throws {
                let host = UIHostingController(rootView: view); window.rootViewController = host; window.overrideUserInterfaceStyle = dark ? .dark : .light; window.makeKeyAndVisible()
                host.view.layoutIfNeeded(); try await Task.sleep(for: .milliseconds(260)); host.view.layoutIfNeeded()
                if bottom {
                    @MainActor func descendants(_ view: UIView) -> [UIView] { [view] + view.subviews.flatMap(descendants) }
                    if let scroll = descendants(host.view).compactMap({ $0 as? UIScrollView }).first(where: { $0.contentSize.height > $0.bounds.height }) {
                        scroll.setContentOffset(.init(x: scroll.contentOffset.x, y: max(0, scroll.contentSize.height - scroll.bounds.height + scroll.adjustedContentInset.bottom)), animated: false)
                        try await Task.sleep(for: .milliseconds(150)); host.view.layoutIfNeeded()
                        scroll.setContentOffset(.init(x: scroll.contentOffset.x, y: max(0, scroll.contentSize.height - scroll.bounds.height + scroll.adjustedContentInset.bottom)), animated: false)
                        try await Task.sleep(for: .milliseconds(100)); host.view.layoutIfNeeded()
                    }
                }
                XCTAssertGreaterThan(host.view.bounds.width, 300); XCTAssertGreaterThan(host.view.bounds.height, 300)
                if let output = ProcessInfo.processInfo.environment["PROOF_DRIVER_PREVIEW_OUTPUT"] {
                    let directory = URL(fileURLWithPath: output); try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
                    let image = UIGraphicsImageRenderer(bounds: window.bounds).image { _ in window.drawHierarchy(in: window.bounds, afterScreenUpdates: true) }
                    let device = UIDevice.current.userInterfaceIdiom == .pad ? "ipad" : "iphone"
                    try image.pngData()?.write(to: directory.appending(path: "pg-parity-\(name)-\(device).png"))
                }
            }
            workspace.browser.tab = .structure; await workspace.browser.loadTable()?.value
            let draft = workspace.schema.draft(for: object)
            XCTAssertNotNil(draft.snapshot); XCTAssertEqual(draft.dialect.descriptor.automaticValueStyle, .identity)
            try await show(MobileTableView(model: workspace.browser, profileID: profile.id, schema: workspace.schema, tableActions: workspace.tableActions), "structure", dark: true)
            try await show(MobileStructureSQLView(sql: draft.snapshot?.ddl ?? ""), "structure-sql")
            let column = try XCTUnwrap(draft.state.columns.first { $0.definition.name == "name" })
            try await show(MobileSchemaColumnEditor(controller: workspace.schema, draft: draft, selection: .init(itemID: column.id, epoch: draft.epoch, section: .columns), close: {}), "column")
            draft.section = .indexes
            let index = try XCTUnwrap(draft.state.indexes.first)
            try await show(MobileSchemaIndexEditor(controller: workspace.schema, draft: draft, selection: .init(itemID: index.id, epoch: draft.epoch, section: .indexes), close: {}), "index", dark: true)
            workspace.newTable.present(database: object.database)
            let new = try XCTUnwrap(workspace.newTable.draft); await workspace.newTable.loadChoices(new)?.value; new.definition.tableName = "待创建表"
            let newID = try XCTUnwrap(new.definition.editor.columns.first); var newDefinition = newID.definition; newDefinition.name = "id"; newDefinition.type = "bigint"; new.definition.editor.updateColumn(id: newID.id, definition: newDefinition)
            try await show(MobileNewTableView(controller: workspace.newTable, draft: new), "new-table")
            try await show(MobileNewTableConfirmation(controller: workspace.newTable, draft: new, plan: new.plan), "new-confirmation")
            XCTAssertFalse(new.definition.availableTabs.contains(.options)); XCTAssertEqual(new.definition.schemaName, schema)
            workspace.newTable.discard(new)
            workspace.openImport(object)
            let importer = try XCTUnwrap(workspace.dataImport)
            let url = FileManager.default.temporaryDirectory.appending(path: "pg-native-\(UUID()).csv"); defer { try? FileManager.default.removeItem(at: url) }
            try Data("id,name\n9007199254740993,导入预览雪\n".utf8).write(to: url)
            importer.select(url); await importer.load()?.value; await importer.prepare()?.value
            XCTAssertNotNil(importer.prepared, importer.message ?? "missing preview")
            try await show(MobileDataImportView(model: importer, close: {}, discard: {}), "import")
            try await show(MobileDataImportView(model: importer, close: {}, discard: {}), "import-confirmation", dark: true, bottom: true)
            workspace.closeImport(discard: true)
            workspace.query.sql = "SELECT id AS row_key,name AS label FROM " + table
            await workspace.query.execute()?.value
            let editing = try XCTUnwrap(workspace.query.editing, workspace.query.editingMessage ?? "missing query editing")
            let page = try XCTUnwrap(workspace.query.editingPage)
            try editing.stage(editing.request(page: page, row: 0, column: 1), text: "待提交 PG 修改", mode: .value)
            try await show(MobilePendingChangesView(changes: editing), "query-pending", dark: true)
            editing.discard(); await workspace.query.disconnectSQL()?.value
            workspace.tableActions.prepare(.rename, object: object)
            let action = try XCTUnwrap(workspace.tableActions.request); action.input = "new.table"
            try await show(MobileTableActionView(controller: workspace.tableActions, draft: action), "table-action")
        }
    }
}
