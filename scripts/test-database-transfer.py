#!/usr/bin/env python3
"""Exercise connection-to-connection transfer with installed drivers and isolated local fixtures.

Uses existing local MySQL demo containers and a temporary PostgreSQL 17 container.
Credentials remain in memory; all generated databases/schemas and the temporary
container are removed on completion. No saved user connections are read.
"""
from pathlib import Path
import json
import os
import platform
import re
import subprocess
import time
import uuid

root = Path(__file__).resolve().parent.parent
docker = '/Applications/Docker.app/Contents/Resources/bin/docker'
dd = root / '.build/DerivedData'
products = dd / 'Build/Products/Debug'
frameworks = products / 'PackageFrameworks'
binary = root / '.build/test-database-transfer'
compiler = '/Applications/Xcode.app/Contents/Developer/Toolchains/XcodeDefault.xctoolchain/usr/bin/swiftc'
developer = subprocess.check_output(['/usr/bin/xcode-select', '-p'], text=True).strip()
args = [compiler, '-parse-as-library', '-target', platform.machine() + '-apple-macosx15.0',
        '-sdk', developer + '/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk',
        str(root / 'scripts/test-database-transfer.swift'), '-I', str(products), '-F', str(frameworks),
        '-framework', 'QueryCraftFeature', '-o', str(binary), '-Xlinker', '-rpath', '-Xlinker', str(frameworks)]
for name in ['TreeSitterJSON', 'TreeSitterSQL', 'TreeSitter', 'Internal', 'CNIOAtomics', 'CNIODarwin', 'CNIOPosix', 'CNIOWindows', 'CNIOWASI', 'CNIOLinux', 'CNIOOpenBSD', 'CNIOLLHTTP']:
    if not (dd / f'Build/Intermediates.noindex/GeneratedModuleMaps/{name}.modulemap').exists():
        continue
    args += ['-Xcc', '-fmodule-map-file=' + str(dd / f'Build/Intermediates.noindex/GeneratedModuleMaps/{name}.modulemap')]
args += ['-Xcc', '-fmodule-map-file=' + str(dd / 'SourcePackages/checkouts/swift-atomics/Sources/_AtomicsShims/include/module.modulemap')]
args += ['-Xcc', '-fmodule-map-file=' + str(dd / 'SourcePackages/checkouts/GRDB.swift/Sources/GRDBSQLite/module.modulemap')]
# Serialized Swift modules can reference shims for other platforms, even when
# their headers are empty on macOS. Discover public source maps as well as the
# platform-specific maps generated by Xcode, deduplicating module declarations.
seen = set()
for index, value in enumerate(args):
    if value.startswith('-fmodule-map-file='):
        path = Path(value.split('=', 1)[1])
        if path.exists():
            match = re.search(r'\bmodule\s+(\w+)', path.read_text())
            if match:
                seen.add(match.group(1))
for path in sorted((dd / 'SourcePackages/checkouts').rglob('module.modulemap')):
    if '/Sources/' not in str(path) or '/Tests/' in str(path):
        continue
    match = re.search(r'\bmodule\s+(\w+)', path.read_text())
    if match and match.group(1) not in seen:
        args += ['-Xcc', '-fmodule-map-file=' + str(path)]
        seen.add(match.group(1))
for path in [root / 'ThirdParty/CodeEditLanguages/Sources/TreeSitterJSON/include',
             root / 'ThirdParty/CodeEditLanguages/Sources/TreeSitterSQL/include',
             dd / 'SourcePackages/checkouts/tree-sitter/lib/include',
             dd / 'SourcePackages/checkouts/TextStory/Sources/Internal',
             root / 'ThirdParty/CodeEditTextView/Sources/CodeEditTextViewObjC/include']:
    args += ['-Xcc', '-I' + str(path)]
subprocess.run(args, check=True)
if os.environ.get('TRANSFER_LOAD_ONLY') == '1':
    env = dict(os.environ, DYLD_FRAMEWORK_PATH=str(frameworks),
               TRANSFER_DRIVER_ROOT=str(Path.home() / 'Library/Application Support/QueryCraftDev/DriverAPI-5/Drivers'))
    subprocess.run([str(binary)], env=env, check=True, timeout=60)
    raise SystemExit(0)


def inspect(name):
    return json.loads(subprocess.check_output([docker, 'inspect', name]))[0]


def mysql(name):
    item = inspect(name)
    variables = dict(v.split('=', 1) for v in item['Config']['Env'] if '=' in v)
    return ('mysql', item['NetworkSettings']['Ports']['3306/tcp'][0]['HostPort'], variables.get('MYSQL_ROOT_PASSWORD', ''))


old = mysql('qc-schema-demo-0b02-source')
new = mysql('qc-schema-demo-0b02-target')
token = uuid.uuid4().hex[:10]
container = 'qc-transfer-pg-' + token
secret = uuid.uuid4().hex
subprocess.run([docker, 'run', '-d', '--name', container, '-e', 'POSTGRES_PASSWORD=' + secret,
                '-p', '127.0.0.1::5432', 'postgres:17'], check=True, stdout=subprocess.DEVNULL)
try:
    for _ in range(60):
        if subprocess.run([docker, 'exec', container, 'pg_isready', '-U', 'postgres'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0:
            break
        time.sleep(0.5)
    else:
        raise RuntimeError('Temporary PostgreSQL did not become ready')
    pg = ('postgresql', inspect(container)['NetworkSettings']['Ports']['5432/tcp'][0]['HostPort'], secret)
    cases = [(old, new), (pg, pg), (old, pg), (pg, new)]
    for index, (source, target) in enumerate(cases):
        if os.environ.get('TRANSFER_CASE') and int(os.environ['TRANSFER_CASE']) != index:
            continue
        env = dict(os.environ, DYLD_FRAMEWORK_PATH=str(frameworks), TRANSFER_TOKEN=token + str(index),
                   TRANSFER_DRIVER_ROOT=str(Path.home() / 'Library/Application Support/QueryCraftDev/DriverAPI-5/Drivers'))
        for label, endpoint in [('SOURCE', source), ('TARGET', target)]:
            env['TRANSFER_' + label + '_TYPE'] = endpoint[0]
            env['TRANSFER_' + label + '_PORT'] = endpoint[1]
            env['TRANSFER_' + label + '_PASSWORD'] = endpoint[2]
        subprocess.run([str(binary)], env=env, check=True, timeout=180)
finally:
    subprocess.run([docker, 'rm', '-f', container], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
